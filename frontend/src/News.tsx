function NewsFigure({ image }: { image: NewsImage }) {
  return <figure className="news-figure">
    <img src={image.src} alt={image.alt} loading="lazy" />
    {image.caption ? <figcaption>{image.caption}</figcaption> : null}
  </figure>;
}

function articleDate(value: string): string {
  return new Date(`${value}T12:00:00`).toLocaleDateString("ru-RU", { day: "numeric", month: "long", year: "numeric" });
}

export function NewsSection() {
  const [showFeatures, setShowFeatures] = useState(true);
  const [showUpdates, setShowUpdates] = useState(false);
  const visibleArticles = newsArticles.filter((article) => "updates" in article ? showUpdates : showFeatures);
  return <section className="panel news-section" aria-labelledby="news-heading">
    <div className="panel-header">
      <div><h2 id="news-heading">Новости</h2><p>Что появилось в Гровике и как этим пользоваться</p></div>
      <div className="news-filters" role="group" aria-label="Категории новостей">
        <button className="news-filter" type="button" aria-pressed={showFeatures}
          title="Большие новости о новых возможностях" onClick={() => setShowFeatures((value) => !value)}>
          <Sparkles size={15} /> Фичи
        </button>
        <button className="news-filter" type="button" aria-pressed={showUpdates}
          title="Короткие доработки и исправления" onClick={() => setShowUpdates((value) => !value)}>
          <Wrench size={15} /> Исправления
        </button>
      </div>
    </div>
    <div className="news-list">{visibleArticles.map((article) => "updates" in article ? <article className="news-updates" key={article.slug}>
      <time dateTime={article.date}>{articleDate(article.date)}</time>
      <h3><a href={`#/news/${article.slug}`}>{article.title}</a></h3>
      <ul>{article.updates.map((text) => <li key={text}>{text}</li>)}</ul>
    </article> : <a className={`news-card${article.image ? "" : " news-card-text"}`} key={article.slug} href={`#/news/${article.slug}`}>
      <div className="news-card-copy">
        <time dateTime={article.date}>{articleDate(article.date)}</time>
        <h3>{article.title}</h3><p>{article.summary}</p>
        <span className="news-read">Как пользоваться <ArrowUpRight size={16} /></span>
      </div>
      {article.image ? <img src={article.image.src} alt="" loading="lazy" /> : null}
    </a>)}</div>
    {!visibleArticles.length ? <p className="muted" role="status">Включите «Фичи» или «Исправления», чтобы увидеть новости.</p> : null}
  </section>;
}

export function NewsPage({ slug }: { slug?: string }) {
  const article = newsArticles.find((item) => item.slug === slug);
  if (!slug) return <NewsSection />;
  if (!article) return <section className="panel"><h1>Новость не найдена</h1><a href="#/">На главную</a></section>;
  if ("updates" in article) return <article className="panel news-article news-updates">
    <a className="news-back" href="#/"><ArrowLeft size={16} /> Все новости на главной</a>
    <header><time dateTime={article.date}>{articleDate(article.date)}</time><h1>{article.title}</h1></header>
    <ul>{article.updates.map((text) => <li key={text}>{text}</li>)}</ul>
  </article>;
  return <article className="panel news-article">
    <a className="news-back" href="#/"><ArrowLeft size={16} /> Все новости на главной</a>
    <header><time dateTime={article.date}>{articleDate(article.date)}</time><h1>{article.title}</h1><p className="news-lead">{article.summary}</p></header>
    {article.image ? <NewsFigure image={article.image} /> : null}
    {article.sections.map((section) => <section key={section.title}>
      <h2>{section.title}</h2>
      {section.paragraphs?.map((text) => <p key={text}>{text}</p>)}
      {section.steps ? <ol>{section.steps.map((text) => <li key={text}>{text}</li>)}</ol> : null}
      {section.image ? <NewsFigure image={section.image} /> : null}
    </section>)}
    <a className="primary" href={article.slug === "test-markup-creation-queue" ? "#/test-markups/create" : "#/dataset-editor"}>{article.slug === "test-markup-creation-queue" ? "Создать тестовую разметку" : "Открыть редактор датасетов"} <ArrowUpRight size={16} /></a>
  </article>;
}
